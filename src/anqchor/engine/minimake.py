"""Makefile generation, ported from ``minimake.py`` and adapted for anqchor.

Each step becomes a rule whose target is a stamp file ``steps/<name>.done``. The
prerequisites are the step's signature file ``steps/<name>.json``, its external
inputs, and the stamps of the steps producing its other inputs. Because a signature
file is rewritten only when its content changes, editing a parameter re-runs exactly
the affected step and everything downstream.

The generated Makefile works with GNU make 3.81 (the macOS default): no grouped
targets, no ``.SHELLFLAGS``, no ``$(file ...)``.
"""

from __future__ import annotations

import contextlib
import hashlib
import json
import os
import re
import shlex
from collections.abc import Iterable
from pathlib import Path

from anqchor.engine.step import Step, StepGraph
from anqchor.util.files import write_text_if_changed

STEPS_DIR = "steps"
LOGS_DIR = "logs"
RECIPE_SHELL = "/bin/bash -eo pipefail"
"""Shell running each step command (the design's ``-euo pipefail`` minus ``-u``, so that
commands may test unset environment variables)."""


class Minimake:
    """Collect make rules and write them out (the original minimake API, kept small)."""

    def __init__(self) -> None:
        self.targets: dict[str, tuple[list[str], list[str]]] = {}
        self.phony: dict[str, list[str]] = {}

    def add_target(self, target: str, sources: Iterable[str], commands: Iterable[str]) -> None:
        """Add a rule. ``commands`` are recipe lines in make syntax (already escaped)."""
        if target in self.targets:
            raise ValueError(f"Target {target} already exists.")
        cmds = list(commands)
        for c in cmds:
            if not isinstance(c, str):
                raise ValueError(f"Command {c!r} for target {target} should be a string.")
        self.targets[target] = (list(sources), cmds)

    def add_phony(self, name: str, sources: Iterable[str]) -> None:
        """Add a phony target depending on ``sources``."""
        self.phony[name] = list(sources)

    def merge(self, other: Minimake) -> None:
        """Add the rules of ``other``; existing targets win."""
        for target, rule in other.targets.items():
            self.targets.setdefault(target, rule)
        for name, sources in other.phony.items():
            self.phony.setdefault(name, sources)

    def render(self, default: str = "all") -> str:
        """Makefile text; ``default`` (when a phony target) is the first rule."""
        lines = [
            "# Makefile generated by anqchor (minimake). Do not edit: it is rewritten on every run.",
            "",
            "SHELL := /bin/bash",
            ".DELETE_ON_ERROR:",
            ".SUFFIXES:",
            "",
        ]
        if self.phony:
            lines.append(".PHONY: " + " ".join(sorted(self.phony)))
            lines.append("")
            if default in self.phony:
                lines.append(f"{default}: " + " ".join(_mk(s) for s in self.phony[default]))
                lines.append("")
            for name in sorted(self.phony):
                if name == default:
                    continue
                lines.append(f"{name}: " + " ".join(_mk(s) for s in self.phony[name]))
            lines.append("")
        for target, (sources, commands) in self.targets.items():
            lines.append(f"{_mk(target)}: " + " ".join(_mk(s) for s in sources))
            for cmd in commands:
                lines.append("\t" + cmd)
            lines.append("")
        return "\n".join(lines)

    def write(self, path: str | Path, default: str = "all") -> bool:
        """Write the Makefile if its content changed; returns True when written."""
        return write_text_if_changed(path, self.render(default))


def _escape_dollar(command: str) -> str:
    """Make interprets ``$``; double it so the shell sees a literal ``$``."""
    return command.replace("$", "$$")


# Characters that GNU make 3.81 cannot take in a target or prerequisite name, even
# escaped (checked with /usr/bin/make 3.81 on macOS): '\\:' is not unescaped in
# prerequisites, '=' turns the rule into a variable assignment, ';' starts a recipe,
# '(' ')' denote archive members, and whitespace other than ' ' splits lines.
_MAKE_UNSAFE = frozenset(":=;()\n\r\t")


def make_safe(path: str | Path) -> bool:
    """True when ``path`` can be written as a make prerequisite (after :func:`_mk`)."""
    s = str(path)
    return not (set(s) & _MAKE_UNSAFE) and not s.endswith("\\")


def _mk(path: str | Path) -> str:
    """Escape a path for use as a make target or prerequisite.

    ``$`` is doubled and spaces and ``#`` are backslash-escaped. Paths for which
    :func:`make_safe` is false cannot be represented; :func:`write_pipeline_makefile`
    replaces such external inputs with a symbolic link under ``steps/inputs``.
    """
    s = str(path).replace("$", "$$")
    for ch in (" ", "#"):
        s = s.replace(ch, "\\" + ch)
    return s


def stamp_path(name: str) -> str:
    """Make target of a step: touched after the step succeeds."""
    return f"{STEPS_DIR}/{name}.done"


def signature_path(name: str) -> str:
    """Command signature of a step (a prerequisite rewritten only when it changes)."""
    return f"{STEPS_DIR}/{name}.json"


INPUT_ALIAS_DIR = f"{STEPS_DIR}/inputs"


def input_alias(path: str | Path, run_dir: Path) -> str:
    """Prerequisite name for the external input ``path``.

    Returns ``path`` itself when make can represent it; otherwise creates (or updates)
    a symbolic link ``steps/inputs/<hash>.<name>`` pointing at it and returns the link.
    make follows symbolic links when it compares modification times.
    """
    if make_safe(path):
        return str(path)
    target = Path(path)
    if not target.is_absolute():
        target = (Path(run_dir) / target).resolve()
    digest = hashlib.sha1(str(target).encode("utf-8")).hexdigest()[:12]
    clean = re.sub(r"[^A-Za-z0-9._-]", "_", target.name)[:60]
    rel = f"{INPUT_ALIAS_DIR}/{digest}.{clean}"
    link = Path(run_dir) / rel
    link.parent.mkdir(parents=True, exist_ok=True)
    if not (link.is_symlink() and os.readlink(link) == str(target)):
        tmp = link.with_name(link.name + ".tmp")
        with contextlib.suppress(FileNotFoundError):
            tmp.unlink()
        os.symlink(str(target), tmp)
        os.replace(tmp, link)
    return rel


def seconds_path(name: str) -> str:
    """File holding the wall time (seconds) of the last successful run of a step."""
    return f"{STEPS_DIR}/{name}.seconds"


def log_path(name: str) -> str:
    """Log file of a step (stdout and stderr of all its commands)."""
    return f"{LOGS_DIR}/{name}.log"


def _recipe(step: Step) -> list[str]:
    """Shell lines for one step: remove the old stamp, create output directories, run
    commands with all output captured to the step log, print the log tail on failure,
    then touch the stamp.

    The stamp is removed first so that it exists only after a fully successful run. A
    forced re-run (``--force``/``--only``, ``make -B``) that fails or is interrupted after
    a command has started rewriting the outputs then leaves the step without a stamp,
    and the next run repeats it (make's ``.DELETE_ON_ERROR`` would not remove a stamp
    whose mtime the failed recipe never changed).

    Commands are shell text, each run by :data:`RECIPE_SHELL`; their ``$`` are doubled
    for make. The wrapper below is written directly in make syntax (``$$`` for the
    shell, ``$@`` for the target)."""
    out_dirs = sorted({str(Path(o).parent) for o in step.outputs} - {"", "."})
    log = log_path(step.name)
    # Each command runs in its own 'bash -eo pipefail -c' with the command as one quoted
    # argument, so shell comments, unbalanced parentheses or 'exit' in a command cannot
    # break or short-circuit the wrapper (the logging and the failure report below).
    body = " && ".join(
        _escape_dollar(f"{RECIPE_SHELL} -c {shlex.quote(c)}") for c in step.all_commands()
    )
    mkdirs = " ".join(_escape_dollar(shlex.quote(d)) for d in [STEPS_DIR, LOGS_DIR, *out_dirs])
    q_log = shlex.quote(log)
    return [
        "@rm -f $@",
        f"@echo '[anqchor] running {step.name}'",
        f"@mkdir -p {mkdirs}",
        "@set -o pipefail; t0=$$(date +%s); "
        f"{{ {body} ; }} > {q_log} 2>&1 || "
        f"{{ rc=$$?; echo '[anqchor] FAILED {step.name} (exit '$$rc'); log: {log}' >&2; "
        f"tail -n 30 {q_log} >&2; exit $$rc; }}; "
        f"echo $$(( $$(date +%s) - t0 )) > {shlex.quote(seconds_path(step.name))}",
        f"@for f in {' '.join(_escape_dollar(shlex.quote(str(o))) for o in step.outputs)}; do "
        'test -e "$$f" || { echo "[anqchor] FAILED '
        f'{step.name} (did not create $$f); log: {log}" >&2; exit 1; }}; done',
        "@touch $@",
    ]


def signature_text(step: Step) -> str:
    """The exact text written to ``steps/<name>.json`` for ``step``."""
    return json.dumps(step.signature(), indent=2, sort_keys=True, default=str) + "\n"


def changed_signatures(graph: StepGraph, run_dir: Path) -> list[str]:
    """Steps whose signature file exists but differs from the current signature."""
    out: list[str] = []
    for step in graph:
        path = Path(run_dir) / signature_path(step.name)
        try:
            if path.read_text(encoding="utf-8") != signature_text(step):
                out.append(step.name)
        except FileNotFoundError:
            pass
    return out


def write_pipeline_makefile(
    graph: StepGraph, run_dir: Path, groups: dict[str, list[str]], *, dry_run: bool = False
) -> Path:
    """Write ``steps/*.json`` signatures and ``Makefile`` for ``graph`` into ``run_dir``.

    Steps whose signature changed, and all steps downstream of them, lose their stamps
    so that the next make invocation re-runs them.

    With ``dry_run`` an existing signature is never rewritten and no stamp is removed
    (only signatures of steps that have none yet are written, since make needs them as
    prerequisites); :func:`changed_signatures` tells the caller which steps would be
    invalidated, so a dry run leaves the run directory's state unchanged.

    Args:
        graph: all steps of the run.
        run_dir: the run directory (make is invoked with ``-C run_dir``).
        groups: phony target name → list of step names (e.g. ``{"match": [...]}``);
            an ``all`` group is added covering every step when absent.
    """
    run_dir = Path(run_dir)
    graph.closure(graph.names())  # raises ValueError on a dependency cycle
    all_groups = dict(groups)
    all_groups.setdefault("all", [s.name for s in graph])
    for gname, members in all_groups.items():
        if gname in graph:
            raise ValueError(f"group name {gname!r} collides with a step name")
        unknown = [m for m in members if m not in graph]
        if unknown:
            raise ValueError(f"group {gname!r} names unknown steps: {', '.join(unknown)}")
    (run_dir / STEPS_DIR).mkdir(parents=True, exist_ok=True)
    (run_dir / LOGS_DIR).mkdir(parents=True, exist_ok=True)
    mm = Minimake()
    changed: list[str] = []
    for step in graph:
        sig_file = run_dir / signature_path(step.name)
        if dry_run and sig_file.exists():
            pass
        elif write_text_if_changed(sig_file, signature_text(step)):
            changed.append(step.name)
        prereqs: list[str] = [signature_path(step.name)]
        for inp in step.inputs:
            prod = graph.producer_of(inp)
            if prod is None:
                alias = input_alias(inp, run_dir)
                if alias not in prereqs:
                    prereqs.append(alias)
            elif prod != step.name:
                st = stamp_path(prod)
                if st not in prereqs:
                    prereqs.append(st)
        mm.add_target(stamp_path(step.name), prereqs, _recipe(step))
        mm.add_phony(step.name, [stamp_path(step.name)])
    for gname, members in all_groups.items():
        mm.add_phony(gname, [stamp_path(m) for m in members])
    # make 3.81 compares mtimes at one-second resolution, so a signature rewritten in
    # the same second as the last run would look up to date. Remove the stamps of
    # changed steps and of everything downstream explicitly.
    stale = set() if dry_run else set(changed)
    for name in list(stale):
        stale.update(graph.downstream(name))
    for name in stale:
        stamp = run_dir / stamp_path(name)
        if stamp.exists():
            stamp.unlink()
    path = run_dir / "Makefile"
    mm.write(path)
    return path
