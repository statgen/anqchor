needs_make = pytest.mark.skipif(shutil.which("make") is None, reason="make not installed")


def sh(name: str, inputs: list[str | Path], outputs: list[str], cmd: str) -> Step:
    return Step(
        name=name,
        inputs=tuple(Path(i) for i in inputs),
        outputs=tuple(Path(o) for o in outputs),
        commands=(cmd,),
    )


# ------------------------------------------------------------------ Minimake API
def test_minimake_api() -> None:
    mm = Minimake()
    mm.add_target("t", ["a b", "c#d"], ["echo hi"])
    with pytest.raises(ValueError, match="already exists"):
        mm.add_target("t", [], [])
    with pytest.raises(ValueError, match="should be a string"):
        mm.add_target("u", [], [1])  # type: ignore[list-item]
    mm.add_phony("all", ["t"])
    other = Minimake()
    other.add_target("t", [], ["ignored"])
    other.add_target("v", [], ["echo v"])
    other.add_phony("grp", ["v"])
    mm.merge(other)
    assert mm.targets["t"][1] == ["echo hi"]  # existing target wins
    text = mm.render()
    lines = text.splitlines()
    assert "SHELL := /bin/bash" in lines
    assert ".DELETE_ON_ERROR:" in lines
    assert ".PHONY: all grp" in lines
    first_rule = next(ln for ln in lines if ln and not ln.startswith(("#", ".", "SHELL")))
    assert first_rule == "all: t"
    assert "t: a\\ b c\\#d" in lines
    assert "\techo hi" in lines


def test_mk_escaping() -> None:
    assert _mk("a b") == "a\\ b"
    assert _mk("x$y") == "x$$y"
    assert _mk("c#d") == "c\\#d"
    assert make_safe("/data/a b/c#d$e.txt")
    for bad in ("/data/run=1/x", "/a:b", "/a;b", "/a(b)", "/a\tb", "/a\\"):
        assert not make_safe(bad)


def test_input_alias(tmp_path: Path) -> None:
    run = tmp_path / "run"
    run.mkdir()
    target = tmp_path / "dir=1" / "f(1).txt"
    target.parent.mkdir()
    target.write_text("x")
    alias = input_alias(target, run)
    assert alias.startswith("steps/inputs/")
    assert make_safe(alias)
    link = run / alias
    assert link.is_symlink() and os.readlink(link) == str(target)
    assert input_alias(target, run) == alias  # stable
    assert input_alias(tmp_path / "plain.txt", run) == str(tmp_path / "plain.txt")


# ------------------------------------------------------------------ rendering
def graph_abc(ext: Path, c_cmd: str = 'x=hello; echo "$x" > c.txt') -> StepGraph:
    return StepGraph(
        [
            sh("s.a", [ext], ["out/a.txt"], f"cat '{ext}' > out/a.txt && echo s.a >> ledger.txt"),
            sh(
                "s.b",
                ["out/a.txt"],
                ["out/b.txt"],
                "cp out/a.txt out/b.txt && echo s.b >> ledger.txt",
            ),
            sh("s.c", ["out/b.txt"], ["c.txt"], c_cmd + " && echo s.c >> ledger.txt"),
        ]
    )


def test_makefile_structure(tmp_path: Path) -> None:
    ext = tmp_path / "in put" / "ext.txt"
    run = tmp_path / "run"
    g = graph_abc(ext)
    path = write_pipeline_makefile(g, run, {"grp": ["s.b", "s.c"]})
    text = path.read_text()
    lines = text.splitlines()
    # make 3.81 portability: no grouped targets, no .SHELLFLAGS, no $(file ...)
    assert "&:" not in text and ".SHELLFLAGS" not in text and "$(file" not in text
    assert lines[0].startswith("# Makefile generated by anqchor")
    assert "SHELL := /bin/bash" in lines
    assert ".DELETE_ON_ERROR:" in lines
    assert ".PHONY: all grp s.a s.b s.c" in lines
    rules = [ln for ln in lines if ln and not ln.startswith(("#", "\t", ".", "SHELL"))]
    assert rules[0] == "all: steps/s.a.done steps/s.b.done steps/s.c.done"
    assert "grp: steps/s.b.done steps/s.c.done" in lines
    assert "s.c: steps/s.c.done" in lines
    # prerequisites: signature, external input (escaped space), producer stamps
    ext_mk = str(ext).replace(" ", "\\ ")
    assert f"steps/s.a.done: steps/s.a.json {ext_mk}" in lines
    assert "steps/s.b.done: steps/s.b.json steps/s.a.done" in lines
    assert "steps/s.c.done: steps/s.c.json steps/s.b.done" in lines
    # the shell '$' of the command is doubled for make
    assert 'x=hello; echo "$$x" > c.txt' in text
    # recipe: status lines, log capture, output check, stamp
    assert "\t@echo '[anqchor] running s.c'" in lines
    assert "> logs/s.c.log 2>&1" in text
    assert "[anqchor] FAILED s.c" in text
    assert "\t@touch $@" in lines
    assert "mkdir -p steps logs out" in text
    # signatures written
    sig = (run / signature_path("s.b")).read_text()
    assert '"name": "s.b"' in sig and "cp out/a.txt" in sig


def test_makefile_rewrite_is_stable(tmp_path: Path) -> None:
    run = tmp_path / "run"
    g = graph_abc(tmp_path / "ext.txt")
    p = write_pipeline_makefile(g, run, {})
    sig = run / signature_path("s.a")
    m1, s1 = p.stat().st_mtime_ns, sig.stat().st_mtime_ns
    time.sleep(0.01)
    write_pipeline_makefile(g, run, {})
    assert p.stat().st_mtime_ns == m1 and sig.stat().st_mtime_ns == s1


def test_group_errors(tmp_path: Path) -> None:
    g = graph_abc(tmp_path / "ext.txt")
    with pytest.raises(ValueError, match="collides with a step name"):
        write_pipeline_makefile(g, tmp_path / "r1", {"s.a": ["s.a"]})
    with pytest.raises(ValueError, match="unknown steps: nope"):
        write_pipeline_makefile(g, tmp_path / "r2", {"grp": ["nope"]})


def test_cycle_rejected(tmp_path: Path) -> None:
    g = StepGraph([sh("x", ["y.txt"], ["x.txt"], "true"), sh("y", ["x.txt"], ["y.txt"], "true")])
    with pytest.raises(ValueError, match="dependency cycle"):
        write_pipeline_makefile(g, tmp_path / "r", {})


# --------------------------------------------------------------- real make runs
def ledger(run: Path) -> list[str]:
    p = run / "ledger.txt"
    out = p.read_text().split() if p.exists() else []
    if p.exists():
        p.unlink()
    return out


def backdate(run: Path, seconds: float = 10) -> None:
    """Move every file of a run back in time, emulating an earlier run. make 3.81 compares
    mtimes at one-second resolution, so tests that change inputs right after a run would
    otherwise depend on the clock."""
    t = time.time() - seconds
    for p in run.rglob("*"):
        if p.is_file() and not p.is_symlink():
            os.utime(p, (t, t))


def run_all(run: Path, **kw: object) -> list[str]:
    res = run_make(run, ["all"], stream=False, **kw)  # type: ignore[arg-type]
    assert res.ok, (res.message, res.failed_step)
    return res.ran


@needs_make
def test_make_incremental_runs(tmp_path: Path) -> None:
    ext = tmp_path / "in put" / "ext.txt"
    ext.parent.mkdir()
    ext.write_text("data\n")
    run = tmp_path / "run dir"  # spaces in the run directory itself
    g = graph_abc(ext)
    write_pipeline_makefile(g, run, {})

    # first run: everything, in order
    assert run_all(run) == ["s.a", "s.b", "s.c"]
    assert ledger(run) == ["s.a", "s.b", "s.c"]
    assert (run / "c.txt").read_text() == "hello\n"  # '$x' reached the shell intact
    assert (run / "out/b.txt").read_text() == "data\n"
    for n in ("s.a", "s.b", "s.c"):
        assert (run / stamp_path(n)).exists()
        assert (run / log_path(n)).exists()
        assert (run / seconds_path(n)).read_text().strip().isdigit()
    assert step_status(g, run) == {n: StepStatus.DONE for n in ("s.a", "s.b", "s.c")}

    # no-op re-run
    write_pipeline_makefile(g, run, {})
    assert run_all(run) == []
    assert ledger(run) == []

    # changed command signature: the step and everything downstream
    g2 = graph_abc(ext, c_cmd='x=hello; echo "$x" > c.txt')
    g2 = StepGraph(
        [
            g.get("s.a"),
            sh(
                "s.b",
                ["out/a.txt"],
                ["out/b.txt"],
                "cp out/a.txt out/b.txt && echo s.b >> ledger.txt # v2",
            ),
            g2.get("s.c"),
        ]
    )
    write_pipeline_makefile(g2, run, {})
    assert step_status(g2, run)["s.b"] == StepStatus.STALE
    assert step_status(g2, run)["s.c"] == StepStatus.STALE
    assert step_status(g2, run)["s.a"] == StepStatus.DONE
    assert run_all(run) == ["s.b", "s.c"]
    assert ledger(run) == ["s.b", "s.c"]

    # deleted output: that step and everything downstream
    (run / "out/b.txt").unlink()
    assert step_status(g2, run)["s.b"] == StepStatus.MISSING
    assert invalidate_missing_outputs(g2, run) == ["s.b"]
    assert not (run / stamp_path("s.c")).exists()
    assert run_all(run) == ["s.b", "s.c"]
    ledger(run)

    # a newer external input re-runs its consumer and everything downstream
    backdate(run)
    ext.write_text("data v2\n")
    assert run_all(run) == ["s.a", "s.b", "s.c"]
    assert (run / "c.txt").exists() and (run / "out/b.txt").read_text() == "data v2\n"
    ledger(run)

    # --force (-B) on one step reruns it and its upstream, not downstream
    assert run_all(run, force=False) == []
    res = run_make(run, ["s.b"], force=True, stream=False)
    assert res.ok and res.ran == ["s.a", "s.b"]
    ledger(run)

    # --only: -B on the step with every upstream stamp assumed old
    res = run_make(run, ["s.b"], force=True, assume_old=["s.a"], stream=False)
    assert res.ok and res.ran == ["s.b"]
    assert ledger(run) == ["s.b"]


@needs_make
def test_make_dry_run_changes_nothing(tmp_path: Path) -> None:
    ext = tmp_path / "ext.txt"
    ext.write_text("x\n")
    run = tmp_path / "run"
    write_pipeline_makefile(graph_abc(ext), run, {})
    res = run_make(run, ["all"], dry_run=True, stream=False)
    assert res.ok
    assert res.ran == []
    assert res.would_run == ["s.a", "s.b", "s.c"]
    assert not (run / "out").exists() and not (run / stamp_path("s.a")).exists()


@needs_make
def test_dry_run_with_changed_signature_leaves_state_untouched(tmp_path: Path) -> None:
    """A dry run with a changed parameter reports the affected steps without rewriting
    signatures or removing stamps, so a later real run with the original parameters
    re-runs nothing."""
    ext = tmp_path / "ext.txt"
    ext.write_text("x\n")
    run = tmp_path / "run"
    g = graph_abc(ext)
    write_pipeline_makefile(g, run, {})
    assert run_all(run) == ["s.a", "s.b", "s.c"]
    ledger(run)
    sig_b = (run / signature_path("s.b")).read_text()
    g2 = StepGraph(
        [
            g.get("s.a"),
            sh(
                "s.b",
                ["out/a.txt"],
                ["out/b.txt"],
                "cp out/a.txt out/b.txt && echo s.b >> ledger.txt # v2",
            ),
            g.get("s.c"),
        ]
    )
    write_pipeline_makefile(g2, run, {}, dry_run=True)
    assert (run / signature_path("s.b")).read_text() == sig_b
    assert all((run / stamp_path(n)).exists() for n in ("s.a", "s.b", "s.c"))
    assert changed_signatures(g2, run) == ["s.b"]
    res = run_make(run, ["all"], dry_run=True, what_if=["s.b"], stream=False)
    assert res.ok and res.would_run == ["s.b", "s.c"]
    # a deleted output in a dry run: reported, stamp kept
    (run / "out/b.txt").unlink()
    assert invalidate_missing_outputs(g, run, dry_run=True) == ["s.b"]
    assert (run / stamp_path("s.c")).exists()
    (run / "out/b.txt").write_text("x\n")
    # back to the original graph: nothing to do
    write_pipeline_makefile(g, run, {})
    assert changed_signatures(g, run) == []
    assert run_all(run) == []


@needs_make
def test_make_failing_step_reports_name_and_log(tmp_path: Path) -> None:
    run = tmp_path / "run"
    g = StepGraph(
        [
            sh("ok", [], ["ok.txt"], "echo fine > ok.txt"),
            sh("boom", ["ok.txt"], ["boom.txt"], "echo 'it broke here' >&2; exit 3"),
            sh("after", ["boom.txt"], ["after.txt"], "touch after.txt"),
        ]
    )
    write_pipeline_makefile(g, run, {})
    res = run_make(run, ["all"], stream=False)
    assert not res.ok
    assert res.ran == ["ok", "boom"]
    assert res.failed_step == "boom"
    assert res.log == run / "logs/boom.log"
    assert "it broke here" in res.log.read_text()
    assert not (run / stamp_path("boom")).exists()
    assert step_status(g, run)["boom"] == StepStatus.MISSING


