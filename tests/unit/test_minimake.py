@needs_make
def test_make_special_characters_in_paths(tmp_path: Path) -> None:
    """Inputs with spaces, '#', '$', '=', ':', '(' and outputs with spaces."""
    weird = tmp_path / "d=1 (copy)" / "a:b #1 $x.txt"
    weird.parent.mkdir()
    weird.write_text("w\n")
    run = tmp_path / "run"
    q = str(weird).replace("'", "'\\''")
    g = StepGraph([sh("w", [weird], ["out dir/o u t.txt"], f"cat '{q}' > 'out dir/o u t.txt'")])
    write_pipeline_makefile(g, run, {})
    res = run_make(run, ["all"], stream=False)
    assert res.ok, res.message
    assert (run / "out dir/o u t.txt").read_text() == "w\n"
    assert run_make(run, ["all"], stream=False).ran == []
    backdate(run)
    weird.write_text("w2\n")  # the new mtime is seen through the alias symlink
    assert run_make(run, ["all"], stream=False).ran == ["w"]
    assert (run / "out dir/o u t.txt").read_text() == "w2\n"


